"""Ideal quadrature (homodyne) measurements without dense projectors.

The harmonic-oscillator wavefunctions are generated by a normalized Hermite
recurrence.  For single-mode pure states only O(chunk_size + cutoff) working storage
is needed, even for sparse Fock states with very large Hilbert-space cutoffs.
Density operators are contracted with a chunk of wavefunctions at a time;
no quadrature projectors or ket outer products are formed.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from numbers import Integral

import numpy as np
from numpy.typing import ArrayLike, NDArray
from scipy.sparse import csr_array

from optiqs.core.q_obj import Qobj, Qtype
from optiqs.measurements.photon_number import (
    _checked_diagonal_numpy,
    _csr_ket_rows,
    _geometry,
)


@dataclass
class _Prepared:
    # Exactly one of coefficients and density is populated.
    coefficients: NDArray[np.complex128] | None
    density: np.ndarray | csr_array | None
    trace: float
    cutoff: int


def _real_parameter(value: float, name: str, *, positive: bool = False) -> float:
    if isinstance(value, (bool, np.bool_)) or np.iscomplexobj(value):
        raise ValueError(f"{name} must be a finite real number")
    try:
        number = float(value)
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError(f"{name} must be a finite real number") from exc
    if not math.isfinite(number) or (positive and number <= 0):
        requirement = "positive finite" if positive else "finite"
        raise ValueError(f"{name} must be a {requirement} real number")
    return number


def _points(values: ArrayLike, *, increasing: bool = False) -> NDArray[np.float64]:
    if np.iscomplexobj(values):
        raise TypeError("xvec must contain real numbers")
    try:
        x = np.asarray(values, dtype=np.float64)
    except (TypeError, ValueError) as exc:
        raise TypeError("xvec must contain real numbers") from exc
    if x.ndim != 1 or x.size < (2 if increasing else 1):
        raise ValueError("xvec must be a one-dimensional array with enough points")
    if not np.all(np.isfinite(x)):
        raise ValueError("xvec must contain only finite values")
    if increasing and not np.all(np.diff(x) > 0):
        raise ValueError("xvec must be strictly increasing for sampling")
    return x


def _positive_integer(value: int, name: str, *, minimum: int = 1) -> int:
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, Integral):
        raise TypeError(f"{name} must be an integer")
    if value < minimum:
        raise ValueError(f"{name} must be at least {minimum}")
    return int(value)


def _prepare(state: Qobj, mode: int) -> _Prepared:
    """Resolve the measured mode and validate/norm the state once."""
    _geometry(
        state, mode
    )  # shares mode and subsystem validation with number measurements
    dims = state.dims[1] if state.qtype == Qtype.bra else state.dims[0]
    if len(dims) > 1:
        # Only the measured mode's marginal is needed.  A sparse reduction
        # remains sparse; a pure one-mode ket is never converted to rho.
        state = state.ptrace(mode)

    data = state._data
    if not isinstance(data, (np.ndarray, csr_array)):
        # The calculation is CPU-based, like optiqs.wigner.  For multimode
        # torch states, ptrace already ran on the original torch device, so
        # only the reduced (cutoff x cutoff) density is transferred.
        data = state.to_numpy()

    if isinstance(data, csr_array):
        if not np.isfinite(data.data).all():
            raise ValueError("state must contain only finite values")
    elif not np.isfinite(data).all():
        raise ValueError("state must contain only finite values")

    if state.is_vector():
        if isinstance(data, csr_array):
            indices = _csr_ket_rows(data) if state.qtype == Qtype.ket else data.indices
            values = data.data if state.qtype == Qtype.ket else data.data.conj()
        else:
            values_all = data.reshape(-1)
            indices = np.flatnonzero(values_all)
            values = values_all[indices]

        if indices.size == 0:
            raise ValueError("state must have positive finite norm")
        amplitudes = np.array(values, dtype=np.complex128, copy=True)
        # Scaling first avoids overflow in the squared norm of an otherwise
        # valid, unnormalized state.
        scale = float(np.max(np.abs(amplitudes)))
        if scale <= 0 or not math.isfinite(scale):
            raise ValueError("state must have positive finite norm")
        amplitudes /= scale
        norm = float(np.linalg.norm(amplitudes))
        if norm <= 0 or not math.isfinite(norm):
            raise ValueError("state must have positive finite norm")
        cutoff = int(np.max(indices)) + 1
        coefficients = np.zeros(cutoff, dtype=np.complex128)
        coefficients[indices] = amplitudes / norm
        return _Prepared(coefficients, None, 1.0, cutoff)

    if isinstance(data, csr_array):
        # Subtraction of Boolean CSR arrays is unsupported and integer
        # subtraction can overflow before the Hermiticity check.
        comparison = data.astype(np.float64) if data.dtype.kind in "biu" else data
        skew = comparison - comparison.conj().T
        if skew.nnz:
            scale = max(1.0, float(np.max(np.abs(data.data), initial=0.0)))
            if float(np.max(np.abs(skew.data))) > 1e-10 * scale:
                raise ValueError("density operator must be Hermitian")
        diagonal = np.asarray(data.diagonal())
    else:
        if not np.allclose(data, data.conj().T, rtol=1e-10, atol=1e-10):
            raise ValueError("density operator must be Hermitian")
        diagonal = np.diagonal(data)

    # Reuse the numerical diagonal checks from photon-number measurements:
    # negative/imaginary entries may not be hidden in a positive trace.
    trace = float(np.sum(_checked_diagonal_numpy(diagonal), dtype=np.float64))
    if not math.isfinite(trace) or trace <= 0:
        raise ValueError("density operator must have positive finite trace")

    if isinstance(data, csr_array):
        # Drop unoccupied high Fock levels without materializing a dense rho.
        rows, cols = data.nonzero()
        if rows.size == 0:
            raise ValueError("density operator must have positive finite trace")
        cutoff = max(int(np.max(rows)), int(np.max(cols))) + 1
        if cutoff < data.shape[0]:
            data = data[:cutoff, :cutoff]
    else:
        cutoff = data.shape[0]
    return _Prepared(None, data, trace, cutoff)


def _vacuum_wavefunction(x: NDArray[np.float64], hbar: float) -> NDArray[np.float64]:
    z = x / math.sqrt(hbar)
    return np.exp(-0.5 * z * z) / (math.pi * hbar) ** 0.25


def _pure_pdf(
    coefficients: NDArray[np.complex128],
    x: NDArray[np.float64],
    theta: float,
    hbar: float,
    chunk_size: int,
) -> NDArray[np.float64]:
    """Accumulate one amplitude using only two Hermite wavefunctions."""
    cutoff = coefficients.size
    phase = np.exp(-1j * theta * np.arange(cutoff))
    rotated = coefficients * phase
    out = np.empty(x.size, dtype=np.float64)
    for start in range(0, x.size, chunk_size):
        stop = min(start + chunk_size, x.size)
        abscissa = x[start:stop] / math.sqrt(hbar)
        previous = _vacuum_wavefunction(x[start:stop], hbar)
        amplitude = rotated[0] * previous
        if cutoff > 1:
            current = math.sqrt(2.0) * abscissa * previous
            for n in range(1, cutoff):
                if rotated[n] != 0:
                    amplitude += rotated[n] * current
                if n + 1 < cutoff:
                    upcoming = (
                        math.sqrt(2.0 / (n + 1)) * abscissa * current
                        - math.sqrt(n / (n + 1)) * previous
                    )
                    previous, current = current, upcoming
        out[start:stop] = np.abs(amplitude) ** 2
    return out


def _mixed_pdf(
    density: np.ndarray | csr_array,
    trace: float,
    cutoff: int,
    x: NDArray[np.float64],
    theta: float,
    hbar: float,
    chunk_size: int,
) -> NDArray[np.float64]:
    """Evaluate <x_theta|rho|x_theta> in bounded-size batches."""
    out = np.empty(x.size, dtype=np.float64)
    phase = None if theta == 0 else np.exp(1j * theta * np.arange(cutoff))
    # rho @ wavefunctions produces one more cutoff x batch array.  Keep the
    # working set bounded even if a huge chunk_size was requested.
    batch_size = max(1, min(chunk_size, 1_000_000 // cutoff))
    for start in range(0, x.size, batch_size):
        stop = min(start + batch_size, x.size)
        abscissa = x[start:stop] / math.sqrt(hbar)
        basis = np.empty((cutoff, stop - start), dtype=np.float64)
        basis[0] = _vacuum_wavefunction(x[start:stop], hbar)
        if cutoff > 1:
            basis[1] = math.sqrt(2.0) * abscissa * basis[0]
        for n in range(1, cutoff - 1):
            basis[n + 1] = (
                math.sqrt(2.0 / (n + 1)) * abscissa * basis[n]
                - math.sqrt(n / (n + 1)) * basis[n - 1]
            )
        rotated = basis if phase is None else phase[:, None] * basis
        result = density @ rotated
        out[start:stop] = (
            np.real(np.einsum("ij,ij->j", rotated.conj(), result, optimize=False))
            / trace
        )
    return out


def _pdf(
    prepared: _Prepared,
    x: NDArray[np.float64],
    theta: float,
    hbar: float,
    chunk_size: int,
) -> NDArray[np.float64]:
    if prepared.coefficients is not None:
        result = _pure_pdf(prepared.coefficients, x, theta, hbar, chunk_size)
    else:
        assert prepared.density is not None
        result = _mixed_pdf(
            prepared.density,
            prepared.trace,
            prepared.cutoff,
            x,
            theta,
            hbar,
            chunk_size,
        )
    if not np.all(np.isfinite(result)):
        raise ValueError("homodyne probability density is not finite")
    # Small roundoff-induced negative values can arise from an otherwise
    # physical, Hermitian mixed state near a zero of the distribution.
    tolerance = 128 * np.finfo(np.float64).eps * float(np.max(np.abs(result)))
    if np.any(result < -tolerance):
        raise ValueError("homodyne probability density must be nonnegative")
    return np.maximum(result, 0.0)


def homodyne_probabilities(
    state: Qobj,
    xvec: ArrayLike,
    mode: int = 0,
    *,
    theta: float = 0.0,
    hbar: float = 1.0,
    chunk_size: int = 4096,
) -> NDArray[np.float64]:
    """Return the ideal homodyne *probability density* p(x | theta).

    The measured quadrature is ``X_theta = sqrt(hbar/2) *
    (a*exp(-1j*theta) + a.dag()*exp(1j*theta))``.  Thus the vacuum PDF
    is ``exp(-x*x/hbar) / sqrt(pi*hbar)``.  ``xvec`` can be any nonempty
    one-dimensional array of finite real quadrature values; the output has
    exactly the same shape and order.  These are *density values*, not
    discrete measurement probabilities.

    Supports single- and multimode kets, bras and density operators, with
    NumPy, SciPy CSR or PyTorch Qobj data.  The measured mode is marginalised
    with ``ptrace`` for multimode states.  PyTorch data is evaluated on CPU,
    with only the reduced density transferred for multimode states.
    Inputs are not modified.  The state is normalized by its norm or trace
    (not by the finite x range); density operators must be Hermitian and
    positive semidefinite for physical results.

    No dense quadrature projector or pure-state outer product is constructed.
    For one-mode kets the cost is O(cutoff*len(xvec)) time and O(cutoff +
    chunk_size) extra memory.  Mixed states use matrix multiplication and
    bounded O(cutoff*chunk_size) working memory.
    """
    theta = math.remainder(_real_parameter(theta, "theta"), 2 * math.pi)
    hbar = _real_parameter(hbar, "hbar", positive=True)
    chunk_size = _positive_integer(chunk_size, "chunk_size")
    x = _points(xvec)
    prepared = _prepare(state, mode)
    return _pdf(prepared, x, theta, hbar, chunk_size)


def measure_homodyne(
    state: Qobj,
    mode: int = 0,
    shots: int = 1,
    *,
    theta: float = 0.0,
    hbar: float = 1.0,
    xvec: ArrayLike | None = None,
    grid_size: int = 4096,
    chunk_size: int = 4096,
    rng: np.random.Generator | int | None = None,
) -> float | NDArray[np.float64]:
    """Sample ideal continuous-valued homodyne outcomes via inverse CDF.

    ``shots`` represents independent identical preparations.  A single shot
    returns a float, multiple shots an array.  The PDF is calculated *once*,
    even for many shots.  A seeded RNG makes sampling reproducible.

    If ``xvec`` is omitted, an automatically sized symmetric grid covers the
    turning point of the highest occupied Fock state plus six vacuum length
    units.  Its resolution is at least ``grid_size`` points and grows with
    the occupied cutoff to resolve higher Hermite oscillations.  If ``xvec``
    is given, it must be strictly increasing with at least two elements;
    samples are conditioned on the specified interval.  In either case the
    CDF is computed by the trapezoid rule, so accuracy depends on the grid.

    A quadrature eigenket is not a normalizable finite-dimensional Qobj;
    unlike photon-number measurement this routine does not return a
    post-measurement state.
    """
    shots = _positive_integer(shots, "shots")
    grid_size = _positive_integer(grid_size, "grid_size", minimum=2)
    chunk_size = _positive_integer(chunk_size, "chunk_size")
    theta = math.remainder(_real_parameter(theta, "theta"), 2 * math.pi)
    hbar = _real_parameter(hbar, "hbar", positive=True)
    if isinstance(rng, (bool, np.bool_)) or not (
        rng is None or isinstance(rng, (Integral, np.random.Generator))
    ):
        raise TypeError("rng must be a NumPy Generator, integer seed, or None")

    prepared = _prepare(state, mode)
    if xvec is None:
        half_width = (math.sqrt(2 * prepared.cutoff - 1) + 6.0) * math.sqrt(hbar)
        # Roughly eight samples per fringe near the highest occupied level.
        size = max(grid_size, 8 * prepared.cutoff + 1)
        x = np.linspace(-half_width, half_width, size)
    else:
        x = _points(xvec, increasing=True)

    pdf = _pdf(prepared, x, theta, hbar, chunk_size)
    dx = np.diff(x)
    interval_masses = 0.5 * (pdf[1:] + pdf[:-1]) * dx
    cdf = np.empty(x.size, dtype=np.float64)
    cdf[0] = 0
    cdf[1:] = np.cumsum(interval_masses)
    mass = float(cdf[-1])
    if not math.isfinite(mass) or mass <= 0:
        raise ValueError("the quadrature grid contains no positive finite probability")
    cdf /= mass
    # Remove flat CDF segments (typically deep tails) before interpolation.
    strictly_increasing = np.r_[True, np.diff(cdf) > 0]
    generator = np.random.default_rng(rng)
    samples = np.interp(
        generator.random(shots), cdf[strictly_increasing], x[strictly_increasing]
    )
    return float(samples[0]) if shots == 1 else samples


__all__ = ["homodyne_probabilities", "measure_homodyne"]
